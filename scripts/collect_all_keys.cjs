  'Geofence Breach (Collar 101)', 'Simulate Battery Drain', 'Live Map Wander',
  'Active Telemetry Simulation', 'Normal (~38.5°)', 'Fever (>40.5°)',
  'High Heart Rate', 'Low Heart Rate', 'High Temperature (Fever)', 'Low Battery Alert',
  'Health Alert', 'New Collar Registered', 'Digital Prescription Received',
