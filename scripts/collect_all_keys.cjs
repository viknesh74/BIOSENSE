const fs = require('fs');
const path = require('path');

const glob = (dir) => fs.readdirSync(dir).reduce((files, file) => {
  const name = path.join(dir, file);
  return fs.statSync(name).isDirectory() ? [...files, ...glob(name)] : [...files, name];
}, []);

const files = glob('src').filter(f => f.endsWith('.jsx') || f.endsWith('.js'));
const allKeys = new Set();
const tamilMap = {};
const hindiMap = {};

// Load existing hindiDictionary
if (fs.existsSync('src/context/hindiDictionary.json')) {
  try {
    const existingHi = JSON.parse(fs.readFileSync('src/context/hindiDictionary.json', 'utf8'));
    Object.assign(hindiMap, existingHi);
  } catch (e) {}
}

// Load extracted_t_calls if exists
if (fs.existsSync('extracted_t_calls.json')) {
  try {
    const extracted = JSON.parse(fs.readFileSync('extracted_t_calls.json', 'utf8'));
    if (extracted.keys) extracted.keys.forEach(k => k && allKeys.add(k));
    if (extracted.tamil) Object.assign(tamilMap, extracted.tamil);
    if (extracted.hindi) Object.assign(hindiMap, extracted.hindi);
  } catch (e) {}
}

// Regex to catch t('en', 'ta', 'hi'...) and variations
const reSingle = /t\(\s*'([^'\\]*(?:\\.[^'\\]*)*)'(?:\s*,\s*'([^'\\]*(?:\\.[^'\\]*)*)')?(?:\s*,\s*'([^'\\]*(?:\\.[^'\\]*)*)')?/g;
const reDouble = /t\(\s*"([^"\\]*(?:\\.[^"\\]*)*)"(?:\s*,\s*"([^"\\]*(?:\\.[^"\\]*)*)")?(?:\s*,\s*"([^"\\]*(?:\\.[^"\\]*)*)")?/g;

files.forEach(f => {
  const content = fs.readFileSync(f, 'utf8');
  let m;
  while ((m = reSingle.exec(content)) !== null) {
    const en = m[1].replace(/\\'/g, "'").trim();
    const ta = m[2] ? m[2].replace(/\\'/g, "'").trim() : '';
    const hi = m[3] ? m[3].replace(/\\'/g, "'").trim() : '';
    if (en && en !== ',' && en !== '') {
      allKeys.add(en);
      if (ta && !tamilMap[en]) tamilMap[en] = ta;
      if (hi && !hindiMap[en]) hindiMap[en] = hi;
    }
  }
  while ((m = reDouble.exec(content)) !== null) {
    const en = m[1].replace(/\\"/g, '"').trim();
    const ta = m[2] ? m[2].replace(/\\"/g, '"').trim() : '';
    const hi = m[3] ? m[3].replace(/\\"/g, '"').trim() : '';
    if (en && en !== ',' && en !== '') {
      allKeys.add(en);
      if (ta && !tamilMap[en]) tamilMap[en] = ta;
      if (hi && !hindiMap[en]) hindiMap[en] = hi;
    }
  }
});

