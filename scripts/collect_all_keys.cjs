extraTerms.forEach(t => allKeys.add(t));

const result = {
  totalKeys: allKeys.size,
  keys: Array.from(allKeys).sort(),
  tamil: tamilMap,
  hindi: hindiMap
};

fs.writeFileSync('all_translation_keys.json', JSON.stringify(result, null, 2));
